-- КонтрОрдер: схема базы данных PostgreSQL
-- Перед запуском создайте базу: CREATE DATABASE kontrorder;
-- Затем: psql -d kontrorder -f db/schema.sql

-- Повторный запуск: удаляем таблицы в обратном порядке зависимостей
DROP TABLE IF EXISTS orders CASCADE;
DROP TABLE IF EXISTS users CASCADE;
DROP TABLE IF EXISTS controller_models CASCADE;

-- 1. Справочник моделей контроллеров
CREATE TABLE controller_models (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE,
    article text NOT NULL UNIQUE,
    controller_type text NOT NULL,
    io_count integer NOT NULL,
    protocol text NOT NULL,
    stock_qty integer NOT NULL DEFAULT 0
);

-- 2. Пользователи: менеджеры, начальники участка и инженеры-наладчики
CREATE TABLE users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name text NOT NULL,
    email text NOT NULL UNIQUE,
    role text NOT NULL
        CONSTRAINT users_role_check
        CHECK (role IN ('Manager', 'Chief', 'Engineer'))
);

-- 3. Главный объект: заказы на контроллеры
-- В таблице хранится внешний ключ model_id, а не повторяющееся название модели (3НФ)
CREATE TABLE orders (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number text NOT NULL UNIQUE,
    title text NOT NULL
        CONSTRAINT orders_title_len_check
        CHECK (char_length(btrim(title)) BETWEEN 5 AND 80),
    description text NOT NULL
        CONSTRAINT orders_description_len_check
        CHECK (char_length(btrim(description)) BETWEEN 10 AND 500),
    model_id integer NOT NULL REFERENCES controller_models (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    status text NOT NULL DEFAULT 'New'
        CONSTRAINT orders_status_check
        CHECK (status IN ('New', 'InProgress', 'Closed', 'Cancelled')),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by_user_id integer NOT NULL REFERENCES users (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    assignee_user_id integer NULL REFERENCES users (id) ON UPDATE CASCADE ON DELETE SET NULL
);

-- Индексы
-- Ускоряет выборку заказов по статусу (WHERE status = 'New') и группировку по статусам (GROUP BY status)
CREATE INDEX orders_status_idx ON orders (status);

-- Ускоряет соединение заказов со справочником моделей и фильтрацию по модели
CREATE INDEX orders_model_id_idx ON orders (model_id);
